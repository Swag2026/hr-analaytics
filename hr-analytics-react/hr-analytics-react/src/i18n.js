const TRANSLATION_KEYS = Object.keys(ARABIC_TO_ENGLISH).sort((a, b) => b.length - a.length);

export function translateText(value) {
  if (value === null || value === undefined || typeof value !== 'string' || !/[\u0600-\u06ff]/.test(value)) return value;
  let result = value;
  TRANSLATION_KEYS.forEach((key) => {
    const isArabicWord = /^[\u0600-\u06ff]+$/.test(key);
    if (isArabicWord) {
      const escaped = key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
      result = result.replace(new RegExp(`(?<![\\u0600-\\u06ff])${escaped}(?![\\u0600-\\u06ff])`, 'g'), ARABIC_TO_ENGLISH[key]);
    } else {
      result = result.split(key).join(ARABIC_TO_ENGLISH[key]);
    }
  });
  return result;
}
